#!/usr/bin/env python3
"""Build the fully client-side version of QUASAR-ARB into ./dist (deployable on Vercel / any static host).

    python static-build/build_static.py

* reference data (tokens, pools, scenarios, sensors, market profiles) is exported from the Python modules -> dist/static/js/data.js
* static-build/engine.js (JS port of core/) is copied next to it
* templates/index.html is rewritten with relative asset paths and the two extra <script> tags
The Python app (app.py + core/) is not modified or imported at runtime by the static site.
"""
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from core import graph_search as g, bayesian_mempool as b, pipeline as p  # noqa: E402

DIST = ROOT / "dist"


def main():
    if DIST.exists():
        shutil.rmtree(DIST)
    shutil.copytree(ROOT / "static", DIST / "static")
    data = {
        "TOKENS": g.TOKENS, "PROTOCOL_GAS_UNITS": g.PROTOCOL_GAS_UNITS, "PROTOCOL_COLORS": g.PROTOCOL_COLORS,
        "PROTOCOL_MEV_BASE": g.PROTOCOL_MEV_BASE, "POOL_DEFS": g.POOL_DEFS, "PROFILES": g.MARKET_PROFILES,
        "SCENARIOS": p.SCENARIOS, "SENSORS": b.SENSORS,
    }
    (DIST / "static/js/data.js").write_text("/* generated by static-build/build_static.py from the Python modules */\nwindow.QUASAR_DATA = "
                                            + json.dumps(data, ensure_ascii=False) + ";\n", encoding="utf-8")
    shutil.copy(ROOT / "static-build/engine.js", DIST / "static/js/engine.js")
    html = (ROOT / "templates/index.html").read_text(encoding="utf-8")
    html = html.replace('"/static/', '"static/')
    html = html.replace('<script src="static/js/app.js"></script>',
                        '<script src="static/js/data.js"></script>\n<script src="static/js/engine.js"></script>\n<script src="static/js/app.js"></script>')
    assert "engine.js" in html and '"/static/' not in html
    (DIST / "index.html").write_text(html, encoding="utf-8")
    (DIST / "vercel.json").write_text('{\n  "cleanUrls": true,\n  "headers": [{"source": "/static/(.*)", "headers": [{"key": "Cache-Control", "value": "public, max-age=3600"}]}]\n}\n')
    size = sum(f.stat().st_size for f in DIST.rglob("*") if f.is_file())
    print(f"dist/ built: {sum(1 for f in DIST.rglob('*') if f.is_file())} files, {size/1e6:.2f} MB")


if __name__ == "__main__":
    main()
